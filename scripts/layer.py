"""Render the overlay alone as a transparent layer for a 16:9 edit in Resolve.

Usage:
  uv run --with fitdecode python -I layer.py <clip.mp4> <ride.fit> [--size 3840x2160] [--codec qtrle|png|prores]
      [--vars '{"showTime":true}'] [--offset S] [--seconds N] [--out <layer.mov>] [--work <dir>]

The layer covers the whole raw clip at the clip's frame rate, so frame N of the layer is frame N
of the clip. On V2 it takes the same source range as the clip on V1 (place_layer.py), and any trim
in Resolve cuts footage and numbers together. It's rendered at the timeline's size (4K by
default), so it lines up with no transform. HyperFrames writes transparent PNG frames and ffmpeg
packs them into a QuickTime file. QuickTime Animation (qtrle) is about 10 Mbps for this mostly
empty frame, against 23 for PNG and 60 for ProRes 4444 (20 s tests on a 4K frame); Resolve reads qtrle
and ProRes with their alpha, PNG-in-MOV as opaque.

Defaults: <clip dir>/ride-overlay/<clip>-layer.mov, project in <clip dir>/ride-overlay/<clip>-layer/.
--seconds renders only the first N seconds, for a quick test. ride_overlay.py --layer calls
make_layer() for every landscape clip in a folder.
"""
import argparse
import glob
import importlib.util
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("reel", os.path.join(HERE, "reel.py"))
reel = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reel)
ride_data = reel.ride_data

CODECS = {
    "qtrle": ["-c:v", "qtrle", "-pix_fmt", "argb"],
    "png": ["-c:v", "copy"],
    "prores": ["-c:v", "prores_ks", "-profile:v", "4444", "-pix_fmt", "yuva444p10le"],
}


def index_html(width, height, seconds, values):
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={width}, height={height}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="assets/ride.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: {width}px; height: {height}px; overflow: hidden; background: transparent; }}
      #root {{ width: 100%; height: 100%; }}
      #overlay {{ position: absolute; left: 0; top: 0; width: {width}px; height: {height}px; }}
    </style>
  </head>
  <body>
    <!-- Generated by ride-overlay/scripts/layer.py: the overlay alone, on a transparent frame. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{seconds}" data-width="{width}" data-height="{height}">
      <div id="overlay" data-composition-id="overlay" data-composition-src="compositions/overlay.html"
        data-variable-values='{json.dumps(values, separators=(",", ":"))}' data-start="0" data-duration="{seconds}"
        data-track-index="0" data-track-kind="graphics" data-width="{width}" data-height="{height}"></div>
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
"""


def make_layer(clip, ride, info, out, work, values, size=(3840, 2160), codec="qtrle", seconds=None, note=""):
    """Render the transparent layer for the clip (or its first `seconds`). Returns the frame count."""
    width, height = size
    seconds = seconds or info["duration"]
    stem = os.path.splitext(os.path.basename(clip))[0]
    os.makedirs(os.path.join(work, "assets"), exist_ok=True)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    ride_data.write_js(ride, os.path.join(work, "assets", "ride.js"), note or f"{stem}, whole clip.")
    reel.write_project(work, width, height, index_html(width, height, round(seconds, 3), values), f"{stem.lower()}-layer")
    reel.lint(work)

    frames = os.path.join(work, "frames")
    shutil.rmtree(frames, ignore_errors=True)
    render = subprocess.run(
        reel.HF + ["render", "--fps", info["fps"], "--format", "png-sequence", "--output", frames],
        cwd=work, env=reel.ENV, capture_output=True, text=True,
    )
    if render.returncode:
        print((render.stdout + render.stderr)[-3000:])
        sys.exit("hyperframes render failed; project left in " + work)
    pngs = sorted(glob.glob(os.path.join(frames, "frame_*.png")))
    first = int(os.path.basename(pngs[0])[6:-4])
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-framerate", info["fps"], "-start_number", str(first), "-i", os.path.join(frames, "frame_%06d.png")]
        + CODECS[codec] + [out],
        check=True,
    )
    shutil.rmtree(frames)
    return len(pngs)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("clip")
    ap.add_argument("fit")
    ap.add_argument("--size", default="3840x2160")
    ap.add_argument("--codec", choices=sorted(CODECS), default="qtrle")
    ap.add_argument("--vars", default="{}")
    ap.add_argument("--offset", type=float, default=0.0, help="seconds to add to the camera's clock")
    ap.add_argument("--seconds", type=float, help="render only the first N seconds (a test)")
    ap.add_argument("--out")
    ap.add_argument("--work")
    a = ap.parse_args()
    clip = os.path.abspath(a.clip)
    stem = os.path.splitext(os.path.basename(clip))[0]

    info = reel.probe(clip)
    if info["h"] > info["w"]:
        sys.exit("portrait clip: make a Reel with reel.py instead")
    ride, nrecs = ride_data.build(a.fit, clip, a.offset)
    print(f"{stem}: {info['w']}x{info['h']}, {info['duration']:.2f} s at {info['fps']}; {nrecs} FIT records")
    if ride_data.missing(ride):
        print("not in this FIT, so the overlay drops it:", ", ".join(ride_data.missing(ride)))

    base = os.path.join(os.path.dirname(clip), "ride-overlay")
    out = os.path.abspath(a.out or os.path.join(base, f"{stem}-layer.mov"))
    work = os.path.abspath(a.work or os.path.join(base, f"{stem}-layer"))
    size = tuple(int(v) for v in a.size.split("x"))
    note = f"{stem}, whole clip, from {os.path.basename(a.fit)}."
    count = make_layer(clip, ride, info, out, work, json.loads(a.vars), size, a.codec, a.seconds, note)
    print(f"wrote {out}: {count} frames ({os.path.getsize(out) / 1e9:.2f} GB)")


if __name__ == "__main__":
    main()
